// ============================================================================
// SCENARIO DOCUMENTATION (Read-only reference — execution in tb_cache_top.sv)
// ============================================================================

// TEST 1 — Cold Cache:
//   Accesses 4 addresses in a cold (fully invalid) cache.
//   EXPECTED: Every access is a compulsory miss.
//   PASS condition: miss_delta == 4, all returned data matches reference model.

// TEST 2 — Temporal Locality:
//   Address 0x0000_4100 accessed 5 times in a row.
//   EXPECTED: access[0]=MISS, access[1..4]=HIT.
//   PASS condition: hit_delta==4, all 5 words identical to reference.

// TEST 3 — Spatial Locality:
//   Addresses 0x5500, 0x5504, 0x5508, 0x550C (same 16-byte block).
//   EXPECTED: First word causes 1 miss, subsequent 3 are hits.
//   PASS condition: miss_delta==1, hit_delta==3, all 4 words correct.

// TEST 4 — Sequential Access:
//   16 sequential word addresses from 0x0600 spanning 4 blocks.
//   EXPECTED: 4 misses (1/block) + 12 hits (3/block).
//   PASS condition: miss_delta==4, hit_delta==12.

// TEST 5 — Conflict Miss:
//   Addresses 0x0000, 0x0400, 0x0800 — all map to index 0.
//   Sequence: a0, a0(hit), a1(evict a0), a0(evict a1), a2(evict a0), a1(evict a2).
//   EXPECTED: 4 conflict misses after the first cold miss.
//   PASS condition: data correct at every access.

// TEST 6 — Random Workload:
//   32 addresses generated by 32-bit Galois LFSR, seed=0xA5A5_1234.
//   EXPECTED: All returned words match reference model.
//   PASS condition: 32/32 data checks pass, reproducible across runs.

// TEST 7 — Reset Behavior:
//   Cache primed with addresses. Hardware reset asserted.
//   EXPECTED: Post-reset first access is a miss (valid bits cleared).
//   PASS condition: hit_out==0 immediately after reset.

// TEST 8 — Consecutive Requests:
//   8 back-to-back reads to 8 different addresses (different indices).
//   EXPECTED: FSM completes each transaction cleanly, no loss/duplication.
//   PASS condition: 8 data-correct responses, fsm returns to IDLE.

`endif // TEST_SCENARIOS_SV
